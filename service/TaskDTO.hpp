#ifndef TASKDTO_HPP
#define TASKDTO_HPP

#include <string>
#include <vector>

//-----------------------------------------------------------------------------
// 【TaskDTO 结构体】
// 【功能】承载单个任务的展示信息（需求 3.1.1、3.1.4），供界面层使用
// 【字段说明】index 为瞬时展示编号（非稳定标识），idValue 为 TaskId 数值
// 【开发者及日期】 QJQ 2026.8.2
//-----------------------------------------------------------------------------
struct TaskDTO
{
    int              index;              // 容器索引（0-based，瞬时展示编号）
    int              idValue;            // TaskId 数值（稳定标识）
    std::string      name;               // 任务名称
    int              duration;           // 工期（0 表示里程碑）
    std::vector<int> predecessorIndices; // 前驱任务索引列表
    std::vector<int> successorIndices;   // 后继任务索引列表
};

#endif
