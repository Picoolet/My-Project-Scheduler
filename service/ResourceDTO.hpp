#ifndef RESOURCEDTO_HPP
#define RESOURCEDTO_HPP

#include <string>

//-----------------------------------------------------------------------------
// 【ResourceDTO 结构体】
// 【功能】承载单个资源的展示信息（需求 3.3.1），供界面层使用
// 【字段说明】index 为瞬时展示编号，idValue 为 ResourceId 数值
// 【开发者及日期】 QJQ 2026.8.2
//-----------------------------------------------------------------------------
struct ResourceDTO
{
    int         index;    // 容器索引（0-based，瞬时展示编号）
    int         idValue;  // ResourceId 数值（稳定标识）
    std::string name;     // 资源名称
    double      unitCost; // 单位时间成本
};

#endif
