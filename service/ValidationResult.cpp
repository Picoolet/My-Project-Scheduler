#include "ValidationResult.hpp"

//-----------------------------------------------------------------------------
// 【ValidationResult::ValidationResult】
// 【函数功能】默认构造函数：空错误列表表示验证通过
// 【参数】无
// 【返回值】无
// 【开发者及日期】 QJQ 2026.8.2
//-----------------------------------------------------------------------------
ValidationResult::ValidationResult()
{
}

//-----------------------------------------------------------------------------
// 【ValidationResult::ValidationResult（带参构造）】
// 【函数功能】从已有错误列表构造，通常传入非空列表表示验证失败
// 【参数】errors — 输入参数，错误信息列表
// 【返回值】无
// 【开发者及日期】 QJQ 2026.8.2
//-----------------------------------------------------------------------------
ValidationResult::ValidationResult(const std::vector<std::string>& errors)
    : m_errors(errors)
{
}

//-----------------------------------------------------------------------------
// 【ValidationResult::AddError】
// 【函数功能】追加一条错误信息
// 【参数】error — 输入参数，错误描述字符串
// 【返回值】无
// 【开发者及日期】 QJQ 2026.8.2
//-----------------------------------------------------------------------------
void ValidationResult::AddError(const std::string& error)
{
    m_errors.push_back(error);
}

//-----------------------------------------------------------------------------
// 【ValidationResult::IsValid】
// 【函数功能】判断验证是否通过
// 【参数】无
// 【返回值】true — 无错误（通过）；false — 存在至少一条错误
// 【开发者及日期】 QJQ 2026.8.2
//-----------------------------------------------------------------------------
bool ValidationResult::IsValid() const
{
    return (m_errors.empty() == true);
}

//-----------------------------------------------------------------------------
// 【ValidationResult::GetErrors】
// 【函数功能】获取全部错误信息列表
// 【参数】无
// 【返回值】错误信息列表的 const 引用
// 【开发者及日期】 QJQ 2026.8.2
//-----------------------------------------------------------------------------
const std::vector<std::string>& ValidationResult::GetErrors() const
{
    return m_errors;
}
