#include "Resource.hpp"

//-----------------------------------------------------------------------------
// 【Resource::Resource】
// 【函数功能】构造资源对象
// 【参数】id — 输入参数，资源唯一标识
//        name — 输入参数，资源名称
//        unitCost — 输入参数，单位时间成本
// 【返回值】无
// 【开发者及日期】 QJQ 2026.7.29
//-----------------------------------------------------------------------------
Resource::Resource(ResourceId id, const std::string& name, double unitCost)
    : m_resourceId(id), m_resourceName(name), m_rUnitCost(unitCost)
{
}

//-----------------------------------------------------------------------------
// 【Resource::GetId】
// 【函数功能】获取资源唯一标识
// 【参数】无
// 【返回值】资源的 ResourceId
// 【开发者及日期】 QJQ 2026.7.29
//-----------------------------------------------------------------------------
ResourceId Resource::GetId() const
{
    return m_resourceId;
}

//-----------------------------------------------------------------------------
// 【Resource::GetName】
// 【函数功能】获取资源名称的只读引用
// 【参数】无
// 【返回值】资源名称的常量引用
// 【开发者及日期】 QJQ 2026.7.29
//-----------------------------------------------------------------------------
const std::string& Resource::GetName() const
{
    return m_resourceName;
}

//-----------------------------------------------------------------------------
// 【Resource::GetUnitCost】
// 【函数功能】获取单位时间成本
// 【参数】无
// 【返回值】单位时间成本（double）
// 【开发者及日期】 QJQ 2026.7.29
//-----------------------------------------------------------------------------
double Resource::GetUnitCost() const
{
    return m_rUnitCost;
}
