#include "Task.hpp"

#include <utility>

//-----------------------------------------------------------------------------
// 【Task::Task】
// 【函数功能】构造任务对象，初始化 ID、名称、工期并创建对应的行为策略
// 【参数】id — 任务唯一标识（由 Project 生成）
//        name — 任务名称
//        duration — 任务工期（>= 0，由调用方保证）
// 【返回值】无
// 【开发者及日期】 QJQ 2026.7.29
//-----------------------------------------------------------------------------
Task::Task(TaskId id, const std::string& name, int duration)
    : m_taskID(id), m_taskName(name), m_iTaskDuration(duration),
      m_pBehavior(ITaskBehavior::Create(duration))
{
}

//-----------------------------------------------------------------------------
// 【Task::GetId】
// 【函数功能】获取任务唯一标识
// 【参数】无
// 【返回值】任务的 TaskId
// 【开发者及日期】 QJQ 2026.7.29
//-----------------------------------------------------------------------------
TaskId Task::GetId() const
{
    return m_taskID;
}

//-----------------------------------------------------------------------------
// 【Task::GetName】
// 【函数功能】获取任务名称的只读引用
// 【参数】无
// 【返回值】任务名称的常量引用
// 【开发者及日期】 QJQ 2026.7.29
//-----------------------------------------------------------------------------
const std::string& Task::GetName() const
{
    return m_taskName;
}

//-----------------------------------------------------------------------------
// 【Task::GetDuration】
// 【函数功能】获取任务工期
// 【参数】无
// 【返回值】工期天数
// 【开发者及日期】 QJQ 2026.7.29
//-----------------------------------------------------------------------------
int Task::GetDuration() const
{
    return m_iTaskDuration;
}

//-----------------------------------------------------------------------------
// 【Task::SetName】
// 【函数功能】修改任务名称
// 【参数】newName — 新名称
// 【返回值】无
// 【开发者及日期】 QJQ 2026.7.29
//-----------------------------------------------------------------------------
void Task::SetName(const std::string& newName)
{
    m_taskName = newName;
}

//-----------------------------------------------------------------------------
// 【Task::SetDuration】
// 【函数功能】修改任务工期，并根据新工期自动切换行为策略
// 【参数】newDuration — 新工期（>= 0，由调用方保证）
// 【返回值】无
// 【开发者及日期】 QJQ 2026.7.29
//-----------------------------------------------------------------------------
void Task::SetDuration(int newDuration)
{
    m_iTaskDuration = newDuration;
    m_pBehavior     = ITaskBehavior::Create(newDuration);
}

//-----------------------------------------------------------------------------
// 【Task::CanAllocateResource】
// 【函数功能】判断任务当前是否可分配资源，委托给行为策略
// 【参数】无
// 【返回值】true 表示可分配，false 表示不可分配（如里程碑任务）
// 【开发者及日期】 QJQ 2026.7.29
//-----------------------------------------------------------------------------
bool Task::CanAllocateResource() const
{
    return m_pBehavior->CanAllocate();
}
