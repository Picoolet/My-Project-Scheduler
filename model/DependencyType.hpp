#ifndef DEPENDENCYTYPE_HPP
#define DEPENDENCYTYPE_HPP

//-----------------------------------------------------------------------------
// 【DependencyType 枚举】
// 【功能】定义任务间时序依赖的四种类型
// 【开发者及日期】 QJQ 2026.7.29
//-----------------------------------------------------------------------------
enum class DependencyType
{
    FS, // Finish-to-Start：前序完成后后继开始
    SS, // Start-to-Start：前序开始后后继开始
    FF, // Finish-to-Finish：前序完成后后继完成
    SF  // Start-to-Finish：前序开始后后继完成
};

#endif
