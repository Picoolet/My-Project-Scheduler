#include "Dependency.hpp"

//-----------------------------------------------------------------------------
// 【Dependency::Dependency】
// 【函数功能】构造依赖关系对象
// 【参数】predecessorId — 输入参数，前序任务 ID
//        successorId — 输入参数，后继任务 ID
//        type — 输入参数，依赖类型
//        lag — 输入参数，时差
// 【返回值】无
// 【开发者及日期】QJQ 2026.7.29
// 【更改记录】 无
//-----------------------------------------------------------------------------
Dependency::Dependency(TaskId predecessorId, TaskId successorId,
                       DependencyType type, int lag)
    : m_predecessorId(predecessorId), m_successorId(successorId), m_type(type),
      m_iLag(lag)
{
}

//-----------------------------------------------------------------------------
// 【Dependency::GetPredecessorId】
// 【函数功能】获取前序任务 ID
// 【参数】无
// 【返回值】前序任务的 TaskId
// 【开发者及日期】QJQ 2026.7.29
// 【更改记录】 无
//-----------------------------------------------------------------------------
TaskId Dependency::GetPredecessorId() const
{
    return m_predecessorId;
}

//-----------------------------------------------------------------------------
// 【Dependency::GetSuccessorId】
// 【函数功能】获取后继任务 ID
// 【参数】无
// 【返回值】后继任务的 TaskId
// 【开发者及日期】QJQ 2026.7.29
// 【更改记录】 无
//-----------------------------------------------------------------------------
TaskId Dependency::GetSuccessorId() const
{
    return m_successorId;
}

//-----------------------------------------------------------------------------
// 【Dependency::GetType】
// 【函数功能】获取依赖类型
// 【参数】无
// 【返回值】DependencyType 枚举值
// 【开发者及日期】QJQ 2026.7.29
// 【更改记录】 无
//-----------------------------------------------------------------------------
DependencyType Dependency::GetType() const
{
    return m_type;
}

//-----------------------------------------------------------------------------
// 【Dependency::GetLag】
// 【函数功能】获取时差
// 【参数】无
// 【返回值】时差整数值，正数为滞后，负数为提前
// 【开发者及日期】QJQ 2026.7.29
// 【更改记录】 无
//-----------------------------------------------------------------------------
int Dependency::GetLag() const
{
    return m_iLag;
}
