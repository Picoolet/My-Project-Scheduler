#ifndef TASKSCHEDULEINFO_HPP
#define TASKSCHEDULEINFO_HPP

//-----------------------------------------------------------------------------
// 【TaskScheduleInfo 结构】
// 【功能】存储单个任务的四个关键路径时间值
// 【开发者及日期】 QJQ 2026.7.29
//-----------------------------------------------------------------------------
struct TaskScheduleInfo
{
    int EarlyStart;  // ES — 最早开始时间
    int EarlyFinish; // EF — 最早完成时间
    int LateStart;   // LS — 最晚开始时间
    int LateFinish;  // LF — 最晚完成时间
};

#endif
