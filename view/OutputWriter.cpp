#include "OutputWriter.hpp"

#include <algorithm>

//-----------------------------------------------------------------------------
// 【OutputWriter::OutputWriter】
// 【函数功能】构造函数，绑定输出流引用
// 【参数】out — 输入参数，目标输出流
// 【返回值】无
// 【开发者及日期】 QJQ 2026.8.5
//-----------------------------------------------------------------------------
OutputWriter::OutputWriter(std::ostream& out) : m_out(out)
{
}

//-----------------------------------------------------------------------------
// 【OutputWriter::Print】
// 【函数功能】原样输出文本（不含换行）
// 【参数】text — 输入参数，待输出文本
// 【返回值】无
// 【开发者及日期】 QJQ 2026.8.5
//-----------------------------------------------------------------------------
void OutputWriter::Print(const std::string& text) const
{
    m_out << text;
}

//-----------------------------------------------------------------------------
// 【OutputWriter::PrintLine】
// 【函数功能】输出一行文本（含换行）
// 【参数】text — 输入参数，待输出文本
// 【返回值】无
// 【开发者及日期】 QJQ 2026.8.5
//-----------------------------------------------------------------------------
void OutputWriter::PrintLine(const std::string& text) const
{
    m_out << text << "\n";
}

//-----------------------------------------------------------------------------
// 【OutputWriter::PrintSuccess】
// 【函数功能】输出成功提示
// 【参数】message — 输入参数，成功信息
// 【返回值】无
// 【开发者及日期】 QJQ 2026.8.5
//-----------------------------------------------------------------------------
void OutputWriter::PrintSuccess(const std::string& message) const
{
    m_out << "  [OK] " << message << "\n";
}

//-----------------------------------------------------------------------------
// 【OutputWriter::PrintError】
// 【函数功能】输出错误提示
// 【参数】message — 输入参数，错误信息
// 【返回值】无
// 【开发者及日期】 QJQ 2026.8.5
//-----------------------------------------------------------------------------
void OutputWriter::PrintError(const std::string& message) const
{
    m_out << "  [FAIL] " << message << "\n";
}

//-----------------------------------------------------------------------------
// 【OutputWriter::PrintWarning】
// 【函数功能】输出警告提示
// 【参数】message — 输入参数，警告信息
// 【返回值】无
// 【开发者及日期】 QJQ 2026.8.5
//-----------------------------------------------------------------------------
void OutputWriter::PrintWarning(const std::string& message) const
{
    m_out << "  [WARN] " << message << "\n";
}

//-----------------------------------------------------------------------------
// 【OutputWriter::PrintHeader】
// 【函数功能】输出带 ═ 分隔线的标题行
// 【参数】title — 输入参数，标题文本
// 【返回值】无
// 【开发者及日期】 QJQ 2026.8.5
//-----------------------------------------------------------------------------
void OutputWriter::PrintHeader(const std::string& title) const
{
    int totalWidth = static_cast<int>(title.length() + 8);

    if (totalWidth < 40)
    {
        totalWidth = 40;
    }

    int side = (totalWidth - static_cast<int>(title.length()) - 2) / 2;

    if (side < 1)
    {
        side = 1;
    }

    m_out << "\n"
          << std::string(static_cast<size_t>(side), '=') << " " << title << " "
          << std::string(static_cast<size_t>(side), '=') << "\n";
}

//-----------------------------------------------------------------------------
// 【OutputWriter::PrintSeparator】
// 【函数功能】输出一行 '─' 分隔线
// 【参数】无
// 【返回值】无
// 【开发者及日期】 QJQ 2026.8.5
//-----------------------------------------------------------------------------
void OutputWriter::PrintSeparator() const
{
    m_out << "  " << std::string(48, '-') << "\n";
}

//-----------------------------------------------------------------------------
// 【OutputWriter::GetStream】
// 【函数功能】获取绑定的输出流
// 【参数】无
// 【返回值】输出流引用
// 【开发者及日期】 QJQ 2026.8.5
//-----------------------------------------------------------------------------
std::ostream& OutputWriter::GetStream() const
{
    return m_out;
}
