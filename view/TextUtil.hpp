#ifndef TEXTUTIL_HPP
#define TEXTUTIL_HPP

#include <string>

//-----------------------------------------------------------------------------
// 【textutil 命名空间】
// 【功能】提供表格对齐与文本截断的公共辅助函数，避免各 Formatter 重复实现
// 【开发者及日期】 QJQ 2026.8.5
//-----------------------------------------------------------------------------
namespace textutil
{

//-----------------------------------------------------------------------------
// 【PadRight】
// 【函数功能】将字符串右填充空格至指定宽度（超出则原样返回）
// 【参数】s — 输入参数，源字符串
//        width — 输入参数，目标宽度
// 【返回值】填充后的字符串
// 【开发者及日期】 QJQ 2026.8.5
//-----------------------------------------------------------------------------
inline std::string PadRight(const std::string& s, int width)
{
    if (static_cast<int>(s.length()) >= width)
    {
        return s;
    }

    return s + std::string(static_cast<size_t>(width - s.length()), ' ');
}

//-----------------------------------------------------------------------------
// 【Truncate】
// 【函数功能】截断超长文本，超过 maxLength 时末尾追加 "..."
// 【参数】s — 输入参数，源字符串
//        maxLength — 输入参数，最大长度
// 【返回值】截断后的字符串
// 【开发者及日期】 QJQ 2026.8.5
//-----------------------------------------------------------------------------
inline std::string Truncate(const std::string& s, int maxLength)
{
    if (static_cast<int>(s.length()) <= maxLength)
    {
        return s;
    }

    return s.substr(0, static_cast<size_t>(maxLength)) + "...";
}

} // namespace textutil

#endif
